import { SLA_HOURS } from "shared";
import { SEED_REQUESTS, SEED_USERS } from "./fixtures";

function sqlString(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function sqlNullable(value: string | null | undefined): string {
  return value === null || value === undefined ? "NULL" : sqlString(value);
}

/** Builds the idempotent seed SQL shared by `pnpm seed` and the benchmark. */
export function buildSeedSql(now = Date.now()): string {
  const createdAtFor = (index: number): string =>
    new Date(now - (index + 1) * 6 * 3_600_000).toISOString();

  const userStatements = SEED_USERS.map((u) => {
    const createdAt = new Date(now - 30 * 86_400_000).toISOString();
    return `INSERT INTO users (id, email, name, role, created_at)
VALUES (${sqlString(u.id)}, ${sqlString(u.email)}, ${sqlString(u.name)}, ${sqlString(u.role)}, ${sqlString(createdAt)})
ON CONFLICT(id) DO UPDATE SET email = excluded.email, name = excluded.name, role = excluded.role;`;
  });

  const requestStatements = SEED_REQUESTS.map((r, index) => {
    const createdAt = createdAtFor(index);
    const dueAt = new Date(
      Date.parse(createdAt) + SLA_HOURS[r.priority] * 3_600_000,
    ).toISOString();
    const resolvedAt =
      r.status === "resolved" || r.status === "rejected"
        ? new Date(Date.parse(createdAt) + 2 * 3_600_000).toISOString()
        : null;
    const breached = resolvedAt === null && Date.parse(dueAt) < now ? 1 : 0;
    return `INSERT INTO requests
  (id, requester_id, title, body, category, priority, status, assignee_id, resolution,
   created_at, updated_at, due_at, sla_breached, resolved_at)
VALUES
  (${sqlString(r.id)}, ${sqlString(r.requesterId)}, ${sqlString(r.title)}, ${sqlString(r.body)},
   ${sqlString(r.category)}, ${sqlString(r.priority)}, ${sqlString(r.status)},
   ${sqlNullable(r.assigneeId)}, ${sqlNullable(r.resolution ?? null)},
   ${sqlString(createdAt)}, ${sqlString(resolvedAt ?? createdAt)}, ${sqlString(dueAt)},
   ${breached}, ${sqlNullable(resolvedAt)})
ON CONFLICT(id) DO UPDATE SET
  title = excluded.title, body = excluded.body, category = excluded.category,
  priority = excluded.priority, status = excluded.status, assignee_id = excluded.assignee_id,
  resolution = excluded.resolution, due_at = excluded.due_at,
  sla_breached = excluded.sla_breached, resolved_at = excluded.resolved_at,
  updated_at = excluded.updated_at;`;
  });

  return [
    "-- Generated by packages/api/scripts/seed.ts. Idempotent, deterministic fixtures.",
    ...userStatements,
    ...requestStatements,
    "",
  ].join("\n");
}
